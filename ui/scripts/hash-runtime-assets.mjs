#!/usr/bin/env node
/**
 * C-3 / D-16 — content hashing for the RUNTIME assets, plus the cache policy
 * that hashing makes safe.
 *
 * WHAT THIS IS FOR
 * ----------------
 * The published folder holds 117 stable-named files the browser fetches at
 * runtime: 105 theme stylesheets, 11 translation files and the favicon. Angular
 * hashes its own bundles (`outputHashing: "all"`) but copies `ui/public`
 * verbatim, so every one of those names is identical in every release. A long
 * cache lifetime on a stable name is a stale-asset bug; no cache lifetime on a
 * stable name is the bandwidth cost this item is about. Both are only
 * unsound in one direction, so the hash has to come first: a release that
 * changes an asset changes its name, and then a one-year `immutable` promise is
 * a true statement.
 *
 * WHAT IT DOES
 * ------------
 *   1. `themes/<id>.css`        -> `themes/<id>.<hash>.css`, and the `css`
 *      field of every `themes/manifest.json` entry is rewritten to the new name
 *      (`ThemeLoader` reads that field, so the app follows automatically).
 *   2. `assets/i18n/<lang>.json` -> `assets/i18n/<lang>.<hash>.json`, plus a
 *      generated `assets/i18n/manifest.json` mapping language -> file, which
 *      `TranslocoHttpLoader` reads before its first request.
 *   3. `favicon.svg`             -> `favicon.<hash>.svg`, and the `<link rel=
 *      "icon">` in `index.html` is rewritten to the new name.
 *   4. `_headers` in the OUTPUT is completed with the policy: one
 *      `Cache-Control: public, max-age=31536000, immutable` rule per hashed
 *      file, and `no-store` for the three entry documents whose names cannot
 *      change (`/`, `/index.html`, and the two generated manifests) plus
 *      `assets/i18n/manifest.json`.
 *
 * WHY PER-FILE RULES AND NOT A WILDCARD
 * --------------------------------------
 * Cloudflare Pages applies every `_headers` rule whose path matches, so a
 * `/themes/*` rule would also match the unhashed `themes/manifest.json` — the
 * one file in that directory whose name is deliberately stable. Emitting the
 * exact hashed paths removes the overlap instead of relying on a precedence
 * rule nobody has verified.
 *
 * IT IS ITS OWN GATE
 * ------------------
 * Every step is verified after it runs and the script exits non-zero on the
 * first failure, so the CI step that invokes it fails the build if a hashed
 * name is missing, if a stable-named runtime asset survives, or if `_headers`
 * did not reach the output. The failure modes this item is about cannot pass
 * silently.
 *
 * Usage: `node ui/scripts/hash-runtime-assets.mjs [outputDir]`
 * (defaults to `ui/dist/ui/browser`, the path CD deploys).
 */
import { createHash } from 'node:crypto';
import { readdir, readFile, rename, rm, writeFile } from 'node:fs/promises';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const UI_DIR = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const OUT = resolve(process.cwd(), process.argv[2] ?? join(UI_DIR, 'dist', 'ui', 'browser'));

/** One year, in seconds — the longest lifetime a browser honours. */
const IMMUTABLE = 'public, max-age=31536000, immutable';
/** The entry documents: the name is stable, so the bytes may change. */
const REVALIDATE = 'no-store';

const fail = (message) => {
  console.error(`❌ ${message}`);
  process.exit(1);
};

/** First 8 hex characters of the SHA-256 of a file's bytes. */
const hashOf = (bytes) => createHash('sha256').update(bytes).digest('hex').slice(0, 8);

/** `<name>.<hash><ext>` — the hash sits before the extension so the MIME type still resolves. */
const hashedName = (name, hash) => {
  const dot = name.lastIndexOf('.');

  return `${name.slice(0, dot)}.${hash}${name.slice(dot)}`;
};

async function readJson(path) {
  return JSON.parse(await readFile(path, 'utf8'));
}

/** Hash every `<id>.css` in the themes directory and rewrite the manifest to match. */
async function hashThemes(immutable) {
  const dir = join(OUT, 'themes');
  const manifestPath = join(dir, 'manifest.json');
  let manifest;

  try {
    manifest = await readJson(manifestPath);
  } catch {
    fail(`${manifestPath} is missing — the theme manifest is generated by \`npm run generate:themes\` (prebuild)`);
  }

  if (!Array.isArray(manifest) || manifest.length === 0) fail('themes/manifest.json is not a non-empty array');

  for (const entry of manifest) {
    const current = join(dir, entry.css);
    let bytes;

    try {
      bytes = await readFile(current);
    } catch {
      fail(`themes/${entry.css} is listed in the manifest but not in the build output`);
    }

    const name = hashedName(entry.css, hashOf(bytes));

    await rename(current, join(dir, name));
    // The manifest is the app's only route to a stylesheet, so rewriting it
    // here is what makes the new name take effect without a code change.
    entry.css = name;
    immutable.push(`/themes/${name}`);
  }

  await writeFile(manifestPath, `${JSON.stringify(manifest, null, 2)}\n`, 'utf8');

  return manifest.length;
}

/** Hash every translation file and write the language -> file map the loader reads. */
async function hashTranslations(immutable) {
  const dir = join(OUT, 'assets', 'i18n');
  const entries = (await readdir(dir)).filter((f) => f.endsWith('.json') && f !== 'manifest.json').sort();

  if (entries.length === 0) fail(`${dir} holds no translation files`);

  const map = {};

  for (const file of entries) {
    const bytes = await readFile(join(dir, file));
    const name = hashedName(file, hashOf(bytes));

    await rename(join(dir, file), join(dir, name));
    map[file.replace(/\.json$/, '')] = name;
    immutable.push(`/assets/i18n/${name}`);
  }

  await writeFile(join(dir, 'manifest.json'), `${JSON.stringify(map, null, 2)}\n`, 'utf8');

  return Object.keys(map).length;
}

/** Hash the favicon and point the document at it. */
async function hashFavicon(immutable) {
  const source = join(OUT, 'favicon.svg');
  let bytes;

  try {
    bytes = await readFile(source);
  } catch {
    fail('favicon.svg is missing from the build output');
  }

  const name = hashedName('favicon.svg', hashOf(bytes));

  await rename(source, join(OUT, name));
  immutable.push(`/${name}`);

  const indexPath = join(OUT, 'index.html');
  const index = await readFile(indexPath, 'utf8');

  if (!index.includes('favicon.svg')) fail('index.html does not reference favicon.svg — nothing to rewrite');

  await writeFile(indexPath, index.replaceAll('favicon.svg', name), 'utf8');

  return name;
}

/**
 * Complete the authored `_headers` (security headers, C-4) with the cache
 * policy. The authored file is read rather than replaced: the two halves are
 * one policy, and a build step that rewrote the file from scratch would let a
 * future edit to the security half be silently dropped.
 */
async function writeHeaders(immutable) {
  const path = join(OUT, '_headers');
  let authored;

  try {
    authored = await readFile(path, 'utf8');
  } catch {
    fail('_headers did not reach the build output — ui/angular.json must copy ui/public verbatim');
  }

  const separator = `\n# ── C-3 / D-16: cache policy for the runtime assets ─────────────────────\n`;
  const policy = [
    separator,
    '# Written by ui/scripts/hash-runtime-assets.mjs, which also produced the',
    '# content-hashed names below. The entry documents keep stable names, so they',
    '# must revalidate; every hashed file may be cached for a year, because a',
    '# change to its bytes changes its name.',
    '/',
    `  Cache-Control: ${REVALIDATE}`,
    '/index.html',
    `  Cache-Control: ${REVALIDATE}`,
    '/themes/manifest.json',
    `  Cache-Control: ${REVALIDATE}`,
    '/assets/i18n/manifest.json',
    `  Cache-Control: ${REVALIDATE}`,
    ...immutable.map((file) => `${file}\n  Cache-Control: ${IMMUTABLE}`),
    '',
  ].join('\n');

  await writeFile(path, `${authored.replace(/\s*$/, '\n')}${policy}`, 'utf8');

  return immutable.length;
}

/** Re-read the output and prove the properties this item claims. */
async function verify(immutable) {
  const headers = await readFile(join(OUT, '_headers'), 'utf8');
  const manifest = await readJson(join(OUT, 'themes', 'manifest.json'));

  const unhashedThemes = manifest.filter((entry) => !/\.[0-9a-f]{8}\.css$/.test(entry.css));

  if (unhashedThemes.length > 0)
    fail(`themes still carry stable names: ${unhashedThemes.map((t) => t.css).join(', ')}`);

  for (const entry of manifest) {
    await readFile(join(OUT, 'themes', entry.css)).catch(() => fail(`themes/${entry.css} is named but absent`));
  }

  const langs = await readJson(join(OUT, 'assets', 'i18n', 'manifest.json'));

  for (const [lang, file] of Object.entries(langs)) {
    await readFile(join(OUT, 'assets', 'i18n', file)).catch(() => fail(`assets/i18n/${file} (${lang}) is absent`));
  }

  for (const file of immutable) {
    if (!headers.includes(`${file}\n  Cache-Control: ${IMMUTABLE}`)) fail(`_headers has no immutable rule for ${file}`);
  }

  // The catch-all: a stable-named file must not have inherited the long lifetime.
  if (!headers.includes(`/index.html\n  Cache-Control: ${REVALIDATE}`)) fail('_headers does not revalidate index.html');

  return { themes: manifest.length, langs: Object.keys(langs).length, rules: immutable.length };
}

const immutable = [];

const themes = await hashThemes(immutable);
const langs = await hashTranslations(immutable);
const favicon = await hashFavicon(immutable);
const rules = await writeHeaders(immutable);
const counts = await verify(immutable);

console.log(
  `🔒 Hashed ${themes} themes, ${langs} translations and ${favicon}; ` +
    `${rules} immutable cache rules written to ${join(OUT, '_headers')} ` +
    `(verified: ${counts.themes}/${counts.langs} names hashed).`,
);
